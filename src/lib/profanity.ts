// Фильтр брани для пользовательского текста (посты, комментарии, истории).
// Бренд «Лапки» — тёплый и семейный: мат на публичных страницах недопустим.
// Ловим и обходы: «п и з д е ц», «пi3дец», латиница-двойники, повторы букв.
// Сознательно консервативен: только жёсткая обсценная лексика, чтобы не было
// ложных срабатываний («употреблять», «оскорблять», «требуется» — чистые).

const LOOKALIKE: Record<string, string> = {
  a: "а", b: "б", c: "с", e: "е", k: "к", m: "м", h: "н", o: "о", p: "р",
  t: "т", x: "х", y: "у", u: "и", i: "и", "3": "з", "0": "о", "4": "ч",
  "6": "б", "9": "д", "@": "а", $: "с",
};

/** Нормализация слова: нижний регистр, ё→е, двойники→кириллица, схлоп повторов. */
function normalizeWord(raw: string): string {
  let s = raw.toLowerCase().replace(/ё/g, "е");
  s = s.replace(/[a-z0-9@$]/g, (c) => LOOKALIKE[c] ?? c);
  s = s.replace(/[^а-я]/g, ""); // внутрисловные разделители/символы
  s = s.replace(/(.)\1{2,}/g, "$1$1"); // «суууука» → «суука»
  return s;
}

// Приставки, после которых корень остаётся бранью («за-», «об-», «недо-»…).
const PREFIX =
  "(?:по|за|на|от|до|пере|при|обо|об|объ|под|съ|раз|разъ|рас|вы|у|из|недо|пре|с|вз|въ|ни|не|о)?";

// Корни. ВАЖНО: «еб»/«бля»/«ху» опасны как подстроки — матчим только от начала
// слова с опциональной приставкой, а не «где угодно в слове».
const ROOTS: RegExp[] = [
  new RegExp(`^${PREFIX}ху[йяеиюе]`),
  new RegExp(`^${PREFIX}пизд`),
  new RegExp(`^${PREFIX}[ея]б(?:ат|ал|ан|ар|ен|ет|еш|ис|ло|ну|ыв|уч|ущ|а$|у$|и$|ы$)`),
  new RegExp(`^${PREFIX}бля(?:д|т|$)`),
  /^мудак|^мудач|^мудил/,
  /^пид[оа]р|^пидр/,
  /^г[ао]ндон/,
  /^залуп/,
  /^шлюх/,
  /^долбо[ея]б|^далбо[ея]б/,
];

function isProfaneWord(word: string): boolean {
  const n = normalizeWord(word);
  if (n.length < 3) return false;
  return ROOTS.some((r) => r.test(n));
}

// Слово с возможной внутрисловной маскировкой: буквы (кир/лат/цифры-двойники),
// разделённые точками/звёздочками/дефисами, считаем одним словом.
const WORD_RE = /[а-яёa-z0-9@$]+(?:[.\-_*]+[а-яёa-z0-9@$]+)*/gi;

/** Есть ли брань в тексте. */
export function hasProfanity(text: string | null | undefined): boolean {
  if (!text) return false;
  const m = text.match(WORD_RE);
  return Boolean(m && m.some(isProfaneWord));
}

/** Цензура: бранные слова → первая буква + звёздочки («п****»). */
export function censorProfanity<T extends string | null | undefined>(text: T): T {
  if (!text) return text;
  return text.replace(WORD_RE, (word) =>
    isProfaneWord(word) ? word[0] + "*".repeat(Math.max(word.length - 1, 2)) : word,
  ) as T;
}
